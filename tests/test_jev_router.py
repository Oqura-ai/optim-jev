class ScanAndInit(unittest.TestCase):
    def test_scan_stops_at_depth_and_skips_vendored(self):
        paths = {e.path for e in scan.scan(project(), 2)}
        self.assertIn("src/core/", paths)
        self.assertNotIn("src/core/pricing/", paths)
        self.assertFalse(any(p.startswith("node_modules") for p in paths))

    def test_init_keeps_only_tree_paths_and_drops_redundant_rules(self):
        root = project()
        req = {"project_dir": str(root), "options": {}, "session_model": "claude-opus-5-5"}
        checks = {"opus": {"id": "claude-opus-5-5", "available": True}, "sonnet": {"id": "", "available": True},
                  "haiku": {"id": "", "available": False}}
        tool.init_save_mode({**req, "reply": REPLY, "checks": checks})
        saved = json.loads((root / ".optim-jev/jev_router/rules.json").read_text())
        self.assertNotIn("notes", saved)
        models = {m["alias"]: m for m in json.loads((root / ".optim-jev/jev_router/models.json").read_text())}
        self.assertEqual((models["sonnet"]["id"], models["haiku"]["available"]), ("", False))
        context = context_mod.load(root)
        self.assertEqual(context.general, ("db/migrations needs opus",))
        self.assertEqual(sorted(context.paths), ["src/core/", "src/gen/"])
        self.assertEqual(sorted(saved["paths"]), ["src/api/", "src/core/", "src/gen/", "tests/"])
        self.assertEqual(saved["paths"]["src/gen/"]["write"], [])
        self.assertEqual(saved["paths"]["tests/"]["write"], ["sonnet", "opus"])  # haiku unavailable: floor moves up
        self.assertEqual(saved["paths"]["tests/"]["delete"], ["opus"])
        self.assertIn("!jev_router/rules.json", (root / ".optim-jev/.gitignore").read_text())
        render_answer = tool.render_mode({**req, "mode": "delegate"})
        self.assertNotIn("haiku", render_answer["tiers"])  # unavailable after the check
        self.assertNotIn("src/core/", render_answer["section"])  # no rules table in the prompt

    def test_unparseable_reply_raises(self):
        with self.assertRaises(ValueError):
            writer.parse_reply("no json here", [], build_ladder("claude-opus-5-5"), {})


class Writer(unittest.TestCase):
    ladder = build_ladder("claude-opus-5-5")
    tiers = {"haiku": 1, "sonnet": 2, "opus": 3}
    tree = [scan.Entry(p, 1, 1) for p in ("src/", "docs/", "tools/", "tests/")]

    def parse(self, reply: str):
        return writer.parse_reply(reply, self.tree, self.ladder, self.tiers)

    def test_scopes_are_open_to_every_model_unless_restricted(self):
        rules, _ = self.parse(
            '{"paths": {"src/": {"why": "core"}, "docs/": {"why": "guides", "min": "none"}, "tools/": {}}}'
        )
        self.assertEqual(rules.paths["src/"].write, ("haiku", "sonnet", "opus"))
        self.assertEqual(rules.paths["docs/"].write, ())
        self.assertNotIn("tools/", rules.paths)  # open and no reason: adds nothing

    def test_context_never_repeats_rules_json(self):
        _, context = self.parse(
            '{"paths": {"src/": {"why": "core logic", "min": "sonnet"}, "docs/": {"why": "guides"}},'
            ' "context": {"general": ["Documentation work only by sonnet or cheaper"],'
            '  "src/": ["needs opus here", "ids are integer cents"], "docs/": ["guides"]}}'
        )
        self.assertEqual(context.general, ("Documentation work only by sonnet or cheaper",))
        self.assertEqual(context.paths, {"src/": ("ids are integer cents",)})

    def test_prompt_carries_the_digest(self):
        text = writer.user_prompt([], "", self.ladder, ["src/a.py  does a thing"])
        self.assertIn("What the main files hold:\nsrc/a.py  does a thing", text)


class Digest(unittest.TestCase):
    def test_first_comment_and_names_not_contents(self):
        root = Path(tempfile.mkdtemp())
        (root / "src").mkdir()
        (root / "src/price.py").write_text(
            '"""Prices in integer cents."""\nSECRET = 1\n\ndef quote(x):\n    pass\n\nclass Engine:\n    pass\n'
        )
        (root / "src/api.ts").write_text("/** Thin HTTP handlers */\nexport function login() {}\nexport const router = 1;\n")
        (root / "README.md").write_text("# The shop\n\ntext\n")
        lines = scan.digest(root)
        self.assertIn("src/price.py  Prices in integer cents. · defines quote, Engine", lines)
        self.assertIn("src/api.ts  Thin HTTP handlers · defines login, router", lines)
        self.assertIn("README.md  The shop", lines)
        self.assertFalse(any("SECRET" in line for line in lines))

    def test_init_refuses_to_overwrite_without_force(self):
        root = project()
        req = {"project_dir": str(root), "options": {}, "session_model": "claude-opus-5-5"}
        self.assertIn("system", tool.scan_mode(req))
        tool.init_save_mode({**req, "reply": REPLY})
        self.assertIn("already has", tool.scan_mode(req)["refused"])
        self.assertIn("system", tool.scan_mode({**req, "force": True}))


class Rules(unittest.TestCase):
    known = ("haiku", "sonnet", "opus")

    def test_min_stands_in_for_write(self):
        rules = rules_mod.parse({"paths": {"a/": {"min": "sonnet"}, "b/": {"min": "none"}, "c/": {"min": "gpt"}}}, self.known)
        self.assertEqual(rules.paths["a/"].write, ("sonnet", "opus"))
        self.assertEqual(rules.paths["b/"].write, ())
        self.assertNotIn("c/", rules.paths)

    def test_validate_names_each_silent_failure(self):
        root = project()
        path = root / ".optim-jev/jev_router/rules.json"
        path.parent.mkdir(parents=True)
        self.assertEqual(rules_mod.validate(root, self.known), [])
        path.write_text('{"paths": {"a/": {"write": ["haiku",]}}}')
        self.assertIn("not valid JSON", rules_mod.validate(root, self.known)[0])
        path.write_text('{"paths": {"a/": {"write": ["Sonnet"]}, "b/": {"why": "x"}, "c/": {"write": ["opus"]}, "d/": {"min": "sonnet"}}}')
        problems = rules_mod.validate(root, self.known)
        self.assertEqual(len(problems), 2)
        self.assertIn("no model may write there", problems[0])
        self.assertIn('"b/"', problems[1])

    def test_section_tells_claude_how_to_keep_the_files(self):
        section = tool.render_mode({"project_dir": str(project()), "options": {}, "session_model": "claude-opus-5-5"})["section"]
        self.assertIn(".optim-jev/jev_router/rules.json", section)
        self.assertIn("Never write it in both", section)
        self.assertIn("haiku, sonnet, opus", section)

    def test_nearest_ancestor_wins(self):
        rules = rules_mod.parse({"paths": {"src/": {"write": ["opus"]}, "src/a/": {"write": ["haiku"]}}}, ("haiku", "sonnet", "opus"))
        self.assertEqual(rules_mod.resolve(rules, "src/a/b/c.py").write, ("haiku",))
        self.assertEqual(rules_mod.resolve(rules, "src/x.py").write, ("opus",))
        self.assertIsNone(rules_mod.resolve(rules, "docs/x.md"))

    def test_context_sections_load_only_for_planned_paths(self):
        ctx = context_mod.parse("# x\n## General\n- g1\n## `src/core/`\n- c1\n## docs/\n- d1\n")
        lines = context_mod.relevant(ctx, ["src/core/db/models.py"])
        self.assertEqual(lines, ["- g1", "src/core/:", "- c1"])
        self.assertEqual(context_mod.parse(context_mod.markdown(ctx)), ctx)


class Spawn(unittest.TestCase):
    def setUp(self):
        self.root = project()
        self.req = {"project_dir": str(self.root), "options": {}, "session_model": "claude-opus-5-5"}
        tool.init_save_mode({**self.req, "reply": REPLY})
        _, self.rules, self.ladder = tool._context(self.req)

    def pick(self, prompt, jev, ladder=None, escalated=None):
        ladder = ladder or self.ladder
        return policy.pick("task", prompt, self.rules, [], ladder, jev, str(self.root), escalated)

    def test_files_named_in_the_prompt_bind_the_choice(self):
        jev = FakeJev({"opus": 0.2, "sonnet": 0.7})
        result = self.pick(f"Add oauth to {self.root / 'src/api/auth.py'} and update README.md", jev)
        self.assertEqual([f.path for f in result.files], ["src/api/auth.py", "README.md"])
        self.assertEqual((result.model, result.source), ("sonnet", "jev"))
        self.assertEqual(sorted(jev.questions["model"]["criteria"]), ["opus", "sonnet"])

    def test_one_allowed_model_skips_jev_and_blocked_files_are_named(self):
        jev = FakeJev({"haiku": 1.0})
        result = self.pick("Index src/core/db.py; regenerate src/gen/pb.py", jev)
        self.assertEqual((result.model, result.source, jev.calls), ("opus", "rules", 0))
        self.assertIn("Never edit: src/gen/", policy.appendix(result, ["- prices are integer cents"], self.ladder))

    def test_jev_failure_falls_back_to_the_session_model(self):
        result = self.pick("Tidy tests/test_a.py", FakeJev(fail=True))
        self.assertEqual((result.model, result.source, result.jev_failed), ("opus", "fallback", "down"))

    def test_cap_keeps_jev_at_or_below_the_session_model(self):
        jev = FakeJev({"opus": 0.9, "sonnet": 0.06, "haiku": 0.04})
        result = self.pick("Fix a typo in README.md", jev, ladder=build_ladder("claude-sonnet-5-5"))
        self.assertEqual(sorted(jev.questions["model"]["criteria"]), ["haiku", "sonnet"])
        self.assertEqual(result.model, "sonnet")

    def test_escalated_files_start_a_model_up(self):
        jev = FakeJev({"haiku": 0.9, "sonnet": 0.1})
        result = self.pick("Fix README.md", jev, escalated={"README.md": 1})
        self.assertEqual((result.model, result.escalated), ("sonnet", 1))

    def test_spawn_mode_logs_and_returns_the_appendix(self):
        answer = tool.spawn_mode({**self.req, "session_id": "s", "description": "core index", "prompt": "Index src/core/db.py"})
        self.assertEqual(answer["model"], "opus")
        self.assertIn("prices are integer cents", answer["appendix"])
        self.assertIn("core index → opus", journal.why(journal.read(self.root, "s"), "s"))
        self.assertTrue((Path(self.root) / ".optim-jev" / "logs" / "jev_router" / "s.jsonl").is_file())


class Journal(unittest.TestCase):
    def test_stats(self):
        root = str(project())
        journal.append(root, "s", {"kind": "spawn", "current": "opus", "model": "haiku", "source": "jev"})
        journal.append(root, "s", {"kind": "outcome", "escalations": [{"from": "haiku", "to": "sonnet"}], "denials": 2})
        from optim_jev.tools.jev_router.catalog import load_catalog
        journal.append(root, "other", {"kind": "spawn", "current": "opus", "model": "opus", "source": "jev"})
        claude = [
            {"kind": "turn", "agent_id": None, "model": "claude-opus-5-5", "input_tokens": 10},
            {"kind": "spawned", "agent_id": "a1", "model": "claude-haiku-4-5"},
            {"kind": "turn", "agent_id": "a1", "model": "claude-haiku-4-5", "input_tokens": 1_000_000},
        ]
        text = journal.stats(journal.read(root, "s"), load_catalog(), claude)
        self.assertIn("haiku 100%", text)
        self.assertIn("on their routed models (measured)   $1.00", text)
        self.assertIn("same tokens on claude-opus-5-5 (est.)   $5.00", text)
        self.assertIn("net saved", text)
        self.assertIn("denied writes: 2", text)


