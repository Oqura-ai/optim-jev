class FakeJev:
    def __init__(self, probabilities: dict[str, float] | None = None, fail: bool = False) -> None:
        self.probabilities = probabilities or {}
        self.fail = fail
        self.calls = 0
        self.questions: dict = {}

    def ask(self, state, questions):
        self.calls += 1
        self.questions = questions
        if self.fail:
            raise policy.JevCompactionError("down")
        return {"answers": {name: {"probabilities": self.probabilities} for name in questions}}


def project() -> Path:
    root = Path(tempfile.mkdtemp())
    for path, size in {
        "src/core/db.py": 5000,
        "src/core/pricing/engine.py": 9000,
        "src/api/auth.py": 800,
        "src/gen/pb.py": 7000,
        "tests/test_a.py": 300,
        "README.md": 200,
        "node_modules/x/y.js": 10,
    }.items():
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        (root / path).write_text("x" * size)
    return root


