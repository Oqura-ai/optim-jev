class ScanAndInit(unittest.TestCase):
    def test_scan_stops_at_depth_and_skips_vendored(self):
        paths = {e.path for e in scan.scan(project(), 2)}
        self.assertIn("src/core/", paths)
        self.assertNotIn("src/core/pricing/", paths)
        self.assertFalse(any(p.startswith("node_modules") for p in paths))

    def test_init_keeps_only_tree_paths_and_drops_redundant_rules(self):
        root = project()
        req = {"project_dir": str(root), "options": {}, "session_model": "claude-opus-5-5"}
        checks = {"opus": {"id": "claude-opus-5-5", "available": True}, "sonnet": {"id": "", "available": True},
                  "haiku": {"id": "", "available": False}}
        tool.init_save_mode({**req, "reply": REPLY, "checks": checks})
        saved = json.loads((root / ".optim-jev/jev_router/rules.json").read_text())
        self.assertNotIn("notes", saved)
        models = {m["alias"]: m for m in json.loads((root / ".optim-jev/jev_router/models.json").read_text())}
        self.assertEqual((models["sonnet"]["id"], models["haiku"]["available"]), ("", False))
        context = context_mod.load(root)
        self.assertEqual(context.general, ("db/migrations needs opus",))
        self.assertEqual(sorted(context.paths), ["src/core/", "src/gen/"])
        self.assertEqual(sorted(saved["paths"]), ["src/api/", "src/core/", "src/gen/", "tests/"])
        self.assertEqual(saved["paths"]["src/gen/"]["write"], [])
        self.assertEqual(saved["paths"]["tests/"]["write"], ["sonnet", "opus"])  # haiku unavailable: floor moves up
        self.assertEqual(saved["paths"]["tests/"]["delete"], ["opus"])
        self.assertIn("!jev_router/rules.json", (root / ".optim-jev/.gitignore").read_text())
        render_answer = tool.render_mode({**req, "mode": "delegate"})
        self.assertNotIn("haiku", render_answer["tiers"])  # unavailable after the check
        self.assertNotIn("src/core/", render_answer["section"])  # no rules table in the prompt

    def test_unparseable_reply_raises(self):
        with self.assertRaises(ValueError):
            writer.parse_reply("no json here", [], build_ladder("claude-opus-5-5"), {})


class Writer(unittest.TestCase):
    ladder = build_ladder("claude-opus-5-5")
    tiers = {"haiku": 1, "sonnet": 2, "opus": 3}
    tree = [scan.Entry(p, 1, 1) for p in ("src/", "docs/", "tools/", "tests/")]

    def parse(self, reply: str):
        return writer.parse_reply(reply, self.tree, self.ladder, self.tiers)

    def test_scopes_are_open_to_every_model_unless_restricted(self):
        rules, _ = self.parse(
            '{"paths": {"src/": {"why": "core"}, "docs/": {"why": "guides", "min": "none"}, "tools/": {}}}'
        )
        self.assertEqual(rules.paths["src/"].write, ("haiku", "sonnet", "opus"))
        self.assertEqual(rules.paths["docs/"].write, ())
        self.assertNotIn("tools/", rules.paths)  # open and no reason: adds nothing

    def test_context_never_repeats_rules_json(self):
        _, context = self.parse(
            '{"paths": {"src/": {"why": "core logic", "min": "sonnet"}, "docs/": {"why": "guides"}},'
            ' "context": {"general": ["Documentation work only by sonnet or cheaper"],'
            '  "src/": ["needs opus here", "ids are integer cents"], "docs/": ["guides"]}}'
        )
        self.assertEqual(context.general, ("Documentation work only by sonnet or cheaper",))
        self.assertEqual(context.paths, {"src/": ("ids are integer cents",)})

    def test_prompt_carries_the_digest(self):
        text = writer.user_prompt([], "", self.ladder, ["src/a.py  does a thing"])
        self.assertIn("What the main files hold:\nsrc/a.py  does a thing", text)


